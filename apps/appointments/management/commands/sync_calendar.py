import logging
from django.core.management.base import BaseCommand
from apps.clinics.models import Clinic
from apps.appointments.models import Appointment
from apps.integrations.google_calendar.service import get_calendar_service

logger = logging.getLogger(__name__)


class Command(BaseCommand):
    help = "Reconciles and synchronizes the local database with Google Calendar."

    def add_arguments(self, parser):
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Show what would be synced without making changes.",
        )
        parser.add_argument(
            "--purge-all-test-events",
            action="store_true",
            help="Purge all test dental appointment events from Google Calendar.",
        )

    def handle(self, *args, **options):
        dry_run = options.get("dry_run", False)
        purge_all = options.get("purge_all_test_events", False)

        clinic = Clinic.objects.first()
        if not clinic:
            self.stderr.write("No clinic found in database.")
            return

        self.stdout.write(f"Synchronizing Clinic: {clinic.name}")

        cal = get_calendar_service()
        service, cal_id = cal._get_service(clinic)

        # 1. Fetch Google Calendar events
        events_result = service.events().list(
            calendarId=cal_id,
            singleEvents=True,
            maxResults=100,
        ).execute()

        cal_events = events_result.get("items", [])
        self.stdout.write(f"Total Google Calendar events found: {len(cal_events)}")

        # 2. Fetch Active DB appointments
        active_appts = Appointment.objects.filter(clinic=clinic).exclude(
            status__in=[Appointment.Status.CANCELLED, Appointment.Status.NO_SHOW]
        )
        active_event_ids = set(
            active_appts.exclude(external_calendar_event_id="").values_list("external_calendar_event_id", flat=True)
        )
        self.stdout.write(f"Active DB appointments with calendar IDs: {len(active_event_ids)}")

        # 3. Reconcile Google Calendar events
        deleted_count = 0
        for ev in cal_events:
            ev_id = ev.get("id")
            summary = ev.get("summary", "")
            start_str = ev.get("start", {}).get("dateTime", ev.get("start", {}).get("date"))

            # Only manage Dental Appointments generated by this system
            is_clinic_event = "Dental Appointment" in summary

            if not is_clinic_event:
                continue

            should_delete = purge_all or (ev_id not in active_event_ids)

            if should_delete:
                if dry_run:
                    self.stdout.write(f"[DRY-RUN] Would delete orphaned event: {ev_id} | {summary} | {start_str}")
                else:
                    try:
                        cal.delete_event(clinic, ev_id)
                        deleted_count += 1
                        self.stdout.write(self.style.SUCCESS(f"Deleted orphaned calendar event: {ev_id} ({summary} at {start_str})"))
                    except Exception as exc:
                        self.stderr.write(f"Error deleting event {ev_id}: {exc}")

        self.stdout.write(self.style.SUCCESS(
            f"\nSync complete! Removed {deleted_count} orphaned events. DB and Google Calendar are now in 100% sync."
        ))
